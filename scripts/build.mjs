/*
 * Build www/ for a given flavour.
 *   release  – no developer tools at all (the file is not shipped)
 *   beta     – developer tools shipped but hidden until the version number is tapped 7 times
 *   dev      – developer tools shipped and shown
 * Usage: node scripts/build.mjs --flavor=release|beta|dev
 */
import { build } from 'esbuild';
import { writeFileSync, copyFileSync, rmSync, existsSync, readFileSync } from 'node:fs';

const flavor = (process.argv.find(a => a.startsWith('--flavor=')) || '--flavor=release').split('=')[1];
if (!['release', 'beta', 'dev'].includes(flavor)) throw new Error('Unknown flavor ' + flavor);
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));

await build({
  entryPoints: ['src/bridge.js'],
  bundle: true,
  format: 'iife',
  target: ['safari15', 'chrome100'],  // Capacitor 8 minimums: iOS 15, Android WebView 100+
  minify: true,
  legalComments: 'none',
  outfile: 'www/js/capacitor.bundle.js',
  // Strip any stray debug logging from bundled plugin code paths we own.
  drop: flavor === 'release' ? ['debugger'] : [],
});

writeFileSync('www/js/build-flags.js',
  '/* generated by scripts/build.mjs — do not edit */\n' +
  `window.AO_BUILD=${JSON.stringify({ flavor, version: pkg.version, devtools: flavor !== 'release', isDevBuild: flavor === 'dev' })};\n`);

const devDest = 'www/js/devtools.js';
if (flavor === 'release') { if (existsSync(devDest)) rmSync(devDest); }
else copyFileSync('dev/devtools.js', devDest);

console.log(`Built www/ (${flavor}, v${pkg.version})`);
